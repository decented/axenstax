fn want(e: &Expect) -> Item {
    match e {
        Expect::Block(id) => Item::Block(*id),
        Expect::Variant(m, s) => Item::Block(building_variants::id_of(*m, *s).expect("variant id")),
        Expect::Tool(t, m) => Item::Tool(Tool::new(*t, *m)),
        Expect::Material(m) => Item::Material(*m),
        Expect::DebugPlan => Item::Plan(crate::plan::PlanData::debug_3x3_stone()),
        Expect::HutPlan => Item::Plan(crate::plan::PlanData::small_hut()),
    }
}

#[test]
fn golden_every_accepted_give_name_still_resolves_to_the_same_item() {
    assert!(GOLDEN.len() > 600, "the golden list lost rows");
    for (name, expect) in GOLDEN {
        let got = resolve_item(name, 1).unwrap_or_else(|e| panic!("'{name}' stopped resolving: {e}"));
        assert_eq!(got.item, want(expect), "'{name}' resolves to a different item");
        assert_eq!(got.count, 1, "'{name}' count");
    }
}

#[test]
fn golden_names_are_unique_so_the_rows_do_not_hide_each_other() {
    let mut seen = std::collections::HashSet::new();
    for (name, _) in GOLDEN {
        assert!(seen.insert(*name), "duplicate golden row '{name}'");
    }
}

#[test]
fn golden_spelling_is_normalised_and_unknown_names_still_fail() {
    // Case and hyphens are folded before lookup.
    for (typed, canon) in [("STONE", "stone"), ("Oak-Log", "oak_log"), ("Wooden-Pickaxe", "wooden_pickaxe")] {
        assert_eq!(resolve_item(typed, 1).unwrap().item, resolve_item(canon, 1).unwrap().item);
    }
    for bad in ["", "nonsense", "stone_pickaxe_extra", "wooden_", "_pickaxe", "air", "iron_stairs", "oak_wall"] {
        assert!(resolve_item(bad, 1).is_err(), "'{bad}' should not resolve");
    }
}

#[test]
fn golden_count_goes_to_stackables_and_is_ignored_for_tools_and_plans() {
    assert_eq!(resolve_item("stone", 7).unwrap().count, 7);
    assert_eq!(resolve_item("coal", 3).unwrap().count, 3);
    assert_eq!(resolve_item("stone", 0).unwrap().count, 1, "count 0 becomes 1");
    assert_eq!(resolve_item("iron_axe", 9).unwrap().count, 1);
    assert_eq!(resolve_item("bow", 9).unwrap().count, 1);
    assert_eq!(resolve_item("hut_plan", 9).unwrap().count, 1);
    // A block named like a material wins (checked first).
    assert!(matches!(resolve_item("copper", 1).unwrap().item, Item::Block(id) if id == block::COPPER_ORE));
}
