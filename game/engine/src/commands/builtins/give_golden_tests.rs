//! Golden test for the `/give` vocabulary: every name `/give` accepts, and the
//! item it resolves to.
//!
//! The rows below were extracted by script from the match arms in `give.rs`
//! before they became name tables, so they say what `/give` did, not what the
//! tables now say. Expected values are written as constants, never computed
//! with the lookup under test. Cross-table shadowing is part of the contract
//! and is pinned as it was: a block wins over a tool, a bow-type tool and a
//! material, so `cable`, `copper_cable` and `nitre` give the BLOCK, and the
//! `CopperCable` material is reached only as `coppercable`.

